func relativeModulesPath(rootDir, fromDir string) (string, error) {
	absRoot, err := filepath.Abs(rootDir)
	if err != nil {
		return "", fmt.Errorf("resolve root dir: %w", err)
	}
	absFrom, err := filepath.Abs(fromDir)
	if err != nil {
		return "", fmt.Errorf("resolve output dir: %w", err)
	}
	rel, err := filepath.Rel(absFrom, filepath.Join(absRoot, "modules"))
	if err != nil {
		return "", fmt.Errorf("calculate relative module path: %w", err)
	}
	return filepath.ToSlash(rel), nil
}

func sanitizeModuleName(name string) string {
	var out strings.Builder
	for _, r := range name {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' {
			out.WriteRune(r)
			continue
		}
		out.WriteRune('_')
	}
	return out.String()
}

func primaryPort(manifest Manifest) int {
	if len(manifest.Ports) == 0 {
		return 80
	}
	return manifest.Ports[0].ContainerPort
}

func primaryPortName(manifest Manifest) string {
	if len(manifest.Ports) == 0 || manifest.Ports[0].Protocol == "" {
		return "tcp"
	}
	return manifest.Ports[0].Protocol
}

func hclMap(values map[string]string, indent int) string {
	if len(values) == 0 {
		return "{}"
	}
	pad := strings.Repeat(" ", indent)
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var out strings.Builder
	out.WriteString("{\n")
	for _, key := range keys {
		out.WriteString(fmt.Sprintf("%s  %s = %s\n", pad, strconv.Quote(key), strconv.Quote(values[key])))
	}
	out.WriteString(pad + "}")
	return out.String()
}

func hclList(values []string, indent int) string {
	if len(values) == 0 {
		return "[]"
	}
	pad := strings.Repeat(" ", indent)
	var out strings.Builder
	out.WriteString("[\n")
	for _, value := range values {
		out.WriteString(fmt.Sprintf("%s  %s,\n", pad, strconv.Quote(value)))
	}
	out.WriteString(pad + "]")
	return out.String()
}

func hclExpressionMap(values map[string]string, indent int) string {
	if len(values) == 0 {
		return "{}"
	}
	pad := strings.Repeat(" ", indent)
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var out strings.Builder
	out.WriteString("{\n")
	for _, key := range keys {
		out.WriteString(fmt.Sprintf("%s  %s = %s\n", pad, strconv.Quote(key), values[key]))
	}
	out.WriteString(pad + "}")
	return out.String()
}

func hclPorts(ports []Port, indent int) string {
	if len(ports) == 0 {
		return "[]"
	}
	pad := strings.Repeat(" ", indent)
	var out strings.Builder
	out.WriteString("[\n")
	for _, port := range ports {
		out.WriteString(pad + "  {\n")
		out.WriteString(fmt.Sprintf("%s    name           = %s\n", pad, strconv.Quote(port.Name)))
		out.WriteString(fmt.Sprintf("%s    container_port = %d\n", pad, port.ContainerPort))
		out.WriteString(fmt.Sprintf("%s    protocol       = %s\n", pad, strconv.Quote(port.Protocol)))
		out.WriteString(pad + "  },\n")
	}
	out.WriteString(pad + "]")
	return out.String()
}

func hclSecrets(secrets map[string]SecretRef, indent int) string {
	if len(secrets) == 0 {
		return "{}"
	}
	pad := strings.Repeat(" ", indent)
	keys := make([]string, 0, len(secrets))
	for key := range secrets {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var out strings.Builder
	out.WriteString("{\n")
	for _, key := range keys {
		ref := secrets[key]
		out.WriteString(fmt.Sprintf("%s  %s = {\n", pad, strconv.Quote(key)))
		out.WriteString(fmt.Sprintf("%s    secret_name = %s\n", pad, strconv.Quote(ref.SecretName)))
		out.WriteString(fmt.Sprintf("%s    secret_key  = %s\n", pad, strconv.Quote(ref.SecretKey)))
		out.WriteString(pad + "  }\n")
	}
	out.WriteString(pad + "}")
	return out.String()
}

func hclResources(resources Resources, indent int) string {
	pad := strings.Repeat(" ", indent)
	var out strings.Builder
	out.WriteString("{\n")
	if resources.CPURequest != "" {
		out.WriteString(fmt.Sprintf("%s  cpu_request    = %s\n", pad, strconv.Quote(resources.CPURequest)))
	}
	if resources.MemoryRequest != "" {
		out.WriteString(fmt.Sprintf("%s  memory_request = %s\n", pad, strconv.Quote(resources.MemoryRequest)))
	}
	if resources.CPULimit != "" {
		out.WriteString(fmt.Sprintf("%s  cpu_limit      = %s\n", pad, strconv.Quote(resources.CPULimit)))
	}
	if resources.MemoryLimit != "" {
		out.WriteString(fmt.Sprintf("%s  memory_limit   = %s\n", pad, strconv.Quote(resources.MemoryLimit)))
	}
	out.WriteString(pad + "}")
	return out.String()
}
