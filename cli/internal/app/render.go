const renderHeader = "# Generated by ClusterForge from apps manifest. Safe to edit."

type RenderOptions struct {
	RootDir string
}

type renderData struct {
	Header          string
	ModuleName      string
	App             Manifest
	EnvName         string
	Environment     config.Environment
	ModulesPath     string
	PrimaryPort     int
	PortName        string
	BindingEnv      map[string]string
	BindingComments []string
}

func Render(rootDir, envName string, env config.Environment, manifest Manifest) (string, error) {
	manifest.ApplyDefaults()
	if err := manifest.Validate(); err != nil {
		return "", err
	}
	if !IsSupportedOrchestrator(env.Orchestrator) {
		return "", fmt.Errorf("unsupported orchestrator %q for app rendering; supported targets are Kubernetes variants and ecs", env.Orchestrator)
	}
	if manifest.CloudIdentity.Enabled && env.Orchestrator != "eks" && env.Orchestrator != "ecs" {
		return "", fmt.Errorf("cloud identity provider %q is not supported for orchestrator %q; the MVP supports EKS IRSA and ECS task roles", manifest.CloudIdentity.Provider, env.Orchestrator)
	}
	outDir := filepath.Join(env.Path, "apps")
	if env.EffectiveLayout() == "stacked" {
		stackPath, err := env.StackPath("apps")
		if err != nil {
			return "", err
		}
		outDir = stackPath
	}
	modulesPath, err := relativeModulesPath(rootDir, outDir)
	if err != nil {
		return "", err
	}
	registry, err := bindings.Load(env.Path)
	if err != nil {
		return "", err
	}
	resolvedBindings, err := bindings.Resolve(registry, manifest.Dependencies)
	if err != nil {
		return "", err
	}
	data := renderData{
		Header:          renderHeader,
		ModuleName:      sanitizeModuleName(manifest.Name),
		App:             manifest,
		EnvName:         envName,
		Environment:     env,
		ModulesPath:     modulesPath,
		PrimaryPort:     primaryPort(manifest),
		PortName:        primaryPortName(manifest),
		BindingEnv:      resolvedBindings.Environment,
		BindingComments: resolvedBindings.Comments,
	}

	tpl, err := template.New("app").Funcs(template.FuncMap{
		"quote":      strconv.Quote,
		"lower":      strings.ToLower,
		"hclMap":     hclMap,
		"hclList":    hclList,
		"hclExprMap": hclExpressionMap,
		"hclPorts":   hclPorts,
		"hclSecrets": hclSecrets,
		"hclRes":     hclResources,
	}).Parse(templateFor(env.Orchestrator))
	if err != nil {
		return "", fmt.Errorf("parse app render template: %w", err)
	}
	var rendered bytes.Buffer
	if err := tpl.Execute(&rendered, data); err != nil {
		return "", fmt.Errorf("render app %s: %w", manifest.Name, err)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return "", fmt.Errorf("create app render directory %s: %w", outDir, err)
	}
	outPath := filepath.Join(outDir, manifest.Name+".tf")
	if err := os.WriteFile(outPath, rendered.Bytes(), 0o644); err != nil {
		return "", fmt.Errorf("write rendered app %s: %w", outPath, err)
	}
	return outPath, nil
}

func templateFor(orchestrator string) string {
	switch orchestrator {
	case "eks", "kubernetes", "k3s", "rke2", "gke", "aks":
		return kubernetesTemplate
	case "ecs":
		return ecsTemplate
	default:
		return ""
	}
}

func IsSupportedOrchestrator(orchestrator string) bool {
	switch orchestrator {
	case "eks", "kubernetes", "k3s", "rke2", "gke", "aks", "ecs":
		return true
	default:
		return false
	}
}

